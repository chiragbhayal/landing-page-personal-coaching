const fs = require('fs');
const path = require('path');

const root = __dirname;
const envPath = path.join(root, '.env');
const outputPath = path.join(root, 'env-config.js');

if (!fs.existsSync(envPath)) {
  throw new Error(`Missing ${envPath}. Copy .env.example to .env first.`);
}

const env = {};
for (const rawLine of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
  const line = rawLine.trim();
  if (!line || line.startsWith('#')) continue;
  const separator = line.indexOf('=');
  if (separator < 1) continue;
  const key = line.slice(0, separator).trim();
  let value = line.slice(separator + 1).trim();
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    value = value.slice(1, -1);
  }
  env[key] = value;
}

if (!env.BACKEND_URL) {
  throw new Error('BACKEND_URL is required in .env.');
}

const output = `// Generated from .env by generate-env-config.js. Do not edit this file directly.\nwindow.__APP_ENV__ = Object.freeze(${JSON.stringify(
  { BACKEND_URL: env.BACKEND_URL },
  null,
  2
)});\n`;

fs.writeFileSync(outputPath, output, 'utf8');
console.log(`Generated ${outputPath}`);
